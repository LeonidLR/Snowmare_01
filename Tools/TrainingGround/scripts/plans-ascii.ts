// S2.3 review gate: writes docs/design/levelgen/S2_3_PLANS.md - three ASCII plans per archetype (office + block) for the designer, drawn from the
// generated buildings (buildings/planAscii.ts). `node scripts/plans-ascii.ts [out.md]` (default: the doc). Deterministic: fixed sizes and seeds.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { applyStory } from '../src/levelgen/buildingStories.ts';
import { routeSummary } from '../src/levelgen/buildingRoutes.ts';
import { validateBuilding } from '../src/levelgen/buildingTraversal.ts';
import type { Draft, Side } from '../src/levelgen/generate.ts';
import { addBuilding, finalizeDraftToLayout } from '../src/levelgen/generate.ts';
import { buildingToAscii } from '../src/levelgen/buildings/planAscii.ts';
import type { GenBuilding, GenLayout } from '../src/levelgen/schema.ts';
import { DEFAULT_PARAMS, LEVEL_HEIGHT } from '../src/levelgen/schema.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');

interface Spec { archetype: 'office' | 'block'; w: number; h: number; floors: number; seed: number; sides?: Side[]; roof?: boolean; cores?: 'high' }

function build(o: Spec): { l: GenLayout; b: GenBuilding } {
  const d: Draft = { walls: [], buildings: [], ladders: [], covers: [], zones: [], routes: [], spawn_points: [], ambush_points: [], patrol_routes: [], mantle_edges: [], keepFree: [], building_plans: true };
  let n = o.seed * 7919;
  const random = (): number => { n = (n * 1103515245 + 12345) & 0x7fffffff; return n / 0x7fffffff; };
  addBuilding(d, 'B_x', [[20.37, 15.21], [20.37 + o.w, 15.21 + o.h]], {
    height: o.floors * LEVEL_HEIGHT, floors: o.floors, enterable: true, roof_walkable: o.roof ?? o.archetype === 'block', stairwell: o.floors > 1, set_piece: 'facade', archetype: o.archetype,
    doorSides: o.sides ?? ['south'], windowSides: ['south', 'north'], partitionRooms: true, ...(o.cores ? { cores: [o.cores] } : {}),
  }, random);
  const l = finalizeDraftToLayout(d, [90, 90], { name: 't', profile: 't', seed: 1, params: { ...DEFAULT_PARAMS, size_m: [90, 90], building_plans: true }, start: [4, 2], end: [36, 58] });
  return { l, b: l.buildings.find((x) => x.id === 'B_x')! };
}

const fence = (s: string): string => '```\n' + s + '\n```\n';
const out: string[] = [];
const P = (s = ''): void => { out.push(s); };

P('# S2.3 review gate - room plans of the office and the block');
P();
P('> Generated by `Tools/TrainingGround/scripts/plans-ascii.ts` from the real generator output (plans toggle on): walls, doors, windows and rooms exactly as');
P('> the generator emits them, 50 cm per character, long side across, **the street at the bottom** (the court side with the stair core on top). Review before S2.4.');
P();
P('Legend: `#` outer wall, `+ - |` partition, `E` outer door (street / court), `w` window, `S` window that is a balcony / fire-escape slot, `U` flat front door');
P('(**closed** by default), `d` room door, `e` enfilade door, `P` stair-pad portal (200, no leaf), `b` balcony door (only after story 4). Rooms: `K` stair core,');
P('`L` landing / corridor, `O` lobby (ground storey: a room with an outer door), a lower-case letter = a flat with a second entry (a loop), an upper-case letter = a **dead-end** flat (one entry),');
P('`r` room, `s` service room, `e` end suite. Same letter = same flat (a flat is 2-3 rooms: back room, front room, and the core bay\'s front room beside it).');
P();

const offices: Spec[] = [
  { archetype: 'office', w: 15.3, h: 11.6, floors: 1, seed: 5 },
  { archetype: 'office', w: 18.1, h: 12.4, floors: 2, seed: 2 },
  { archetype: 'office', w: 12.6, h: 10.2, floors: 2, seed: 7, cores: 'high' },
];
P('## Offices (S2.2, unchanged by S2.3)');
P();
offices.forEach((o, i) => {
  const { l, b } = build(o);
  const v = validateBuilding(l, b);
  P(`### Office ${i + 1}: ${o.w} x ${o.h} m, ${o.floors} storey${o.floors > 1 ? 's' : ''}, plan \`${b.plan?.kind}\` ${b.plan?.variant ?? ''}`);
  P();
  P(`${(b.rooms ?? []).filter((r) => r.floor === 0).length} rooms per storey; validator issues: ${v.issues.length}.`);
  P();
  for (let f = 0; f < o.floors; ++f) { P(`Storey ${f + 1}${f === 0 ? ' (ground)' : ''}:`); P(); P(fence(buildingToAscii(b, f))); }
});

const blocks: (Spec & { title: string; note: string; escape?: boolean })[] = [
  { archetype: 'block', w: 18.4, h: 10.3, floors: 2, seed: 4, title: 'Block 10 x 18 m, 2 storeys (one section)', note: 'The small block: 350 core, landing 250, flats of 4-5 m.', escape: true },
  { archetype: 'block', w: 20.2, h: 14.1, floors: 3, seed: 6, title: 'Block 14 x 20 m, 3 storeys (one section)', note: 'The biggest lot block: deeper flats, 3 storeys (storey 3 repeats storey 2).' },
  { archetype: 'block', w: 36.5, h: 12.2, floors: 2, seed: 4, title: 'Block 12 x 36 m, 2 storeys (two sections, an engine fixture)', note: 'Two sections side by side, each with its own core and entrances; a wall without a door between them (they meet on the roof). The lot template for blocks this long waits for Q6.' },
];
P('## Blocks (S2.3)');
P();
for (const o of blocks) {
  const { l, b } = build(o);
  const v = validateBuilding(l, b);
  const units = b.units ?? [];
  P(`### ${o.title}`);
  P();
  P(`${o.note} Plan \`${b.plan?.kind}\` / \`${b.plan?.variant}\`, ${b.plan?.sections} section(s); ${(b.rooms ?? []).filter((r) => r.floor === 0).length} rooms per storey; flats per storey ${units.filter((u) => u.floor === 0).length}, `
    + `dead ends ${units.filter((u) => u.floor === 1 && u.dead_end).map((u) => `${u.id.replace(/^B_x_u_f1_/, '')} (run ${u.run_cm} cm)`).join(', ') || '-'}; validator issues: ${v.issues.length}; rooms reachable ${v.rooms.reachable} of ${v.rooms.total}.`);
  P();
  for (const f of [0, 1]) { P(`Storey ${f + 1}${f === 0 ? ' (ground: a street lobby and a court lobby per section)' : ''}:`); P(); P(fence(buildingToAscii(b, f))); }
  if (o.escape) {
    const res = applyStory(l, b, 'rubble_escape', 9);
    if (res.ok) {
      const l2: GenLayout = { ...l, ladders: res.ladders ?? l.ladders, buildings: l.buildings.map((x) => (x.id === b.id ? res.building : x)) };
      P(`Story 4 (rubble on the stair + fire escape) on this block - \`${res.instance.bricks.join(' + ')}\`; the key route's modes: ${routeSummary(l2, res.building)!.modes.join(' - ')}. Storey 2 after the story (\`b\` = the balcony door that replaced the flat's slot window; the fire-escape ladder stands outside it):`);
      P();
      P(fence(buildingToAscii(res.building, 1)));
    }
  }
}

