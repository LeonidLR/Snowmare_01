"""Formation Lab test map (docs/design/FORMATION_SECTORS.md "Test lab", FORMATION_CONTRACT.md 1; coordinator stage 5):
builds /Game/Maps/L_FormationLab from the layout JSON Content/Data/FormationLab/formation_lab_01.json - the SAME file the
Training Ground simulator / movement bot reads (generated by Tools/TrainingGround/src/movement/cli/genLab.ts).

Places (every actor tagged FormationLab and filed under the outliner folder FormationLab/...):
  - a floor slab over the layout bounds (top at ground_z), engine cube + the world grid material (1 m grid);
  - one wall per layout wall: an engine cube along a -> b (length x thickness x height), label = the wall id;
  - PlayerStart at spawn (yaw, 100 cm up);
  - NavMeshBoundsVolume over the bounds (the navmesh: Scripts/bake_navmesh.ps1 after this script);
  - a TargetPoint per route point, label "<route id>_<n>" (e.g. R_A_open_0), tags FormationLab + FormationLabRoute + the route id
    (the in-game bot finds its click path by these);
  - a TextRenderActor per zone (its id, flat on the ground) for screenshots;
  - props: heat_source -> ACampfireActor (unlit: an operative kindles it with a match), else a TargetPoint;
  - v2.1: a TargetPoint per route threat, label "<route id>_threat_<n>", tags FormationLab + FormationLabThreat + the route id
    (the in-game bot reports it to the squad as a known threat at since_s; FORMATION_CONTRACT.md 10.2).
Lighting (sun, sky light, sky atmosphere, height fog) is tagged FormationLab_Env and placed only when missing, so hand tweaks stay.

Idempotent: every run deletes the actors tagged FormationLab and places them again from the JSON; nothing else in the map is
touched and no other map is opened for writing. The map is created (EditorLoadingAndSavingUtils.new_blank_map) when it does not
exist; CODEX_LAB_FRESH=1 deletes it first. The saved RecastNavMesh actors are destroyed before the save (docs/port/TRAPS.md: a
commandlet-saved navmesh stays empty at runtime) - bake it with Scripts/bake_navmesh.ps1 (or open + save the map in the editor).

Env: CODEX_LAB_LAYOUT (layout JSON path, default formation_lab_01), CODEX_LAB_TARGET (map, default /Game/Maps/L_FormationLab),
CODEX_LAB_FRESH=1. Report: Saved/Logs/FormationLabLayout.txt.
Run (this project's editor closed):
  UnrealEditor-Cmd.exe <project>/CodexTactics.uproject -run=pythonscript -script="<abs path to this file>" -unattended -nullrhi
Without Unreal (system python): `python build_formation_lab.py plan [layout.json]` prints the actor plan as JSON (no map change).
"""
import datetime
import json
import math
import os
import sys

try:
    import unreal
except ImportError:  # system python: the `plan` mode only
    unreal = None

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.abspath(os.path.join(HERE, "..", ".."))
DEFAULT_LAYOUT = os.path.join(PROJECT_DIR, "Content", "Data", "FormationLab", "formation_lab_01.json")
LAYOUT_FILE = os.environ.get("CODEX_LAB_LAYOUT", DEFAULT_LAYOUT)
TARGET_MAP = os.environ.get("CODEX_LAB_TARGET", "/Game/Maps/L_FormationLab")
TAG = "FormationLab"
ENV_TAG = "FormationLab_Env"
ROUTE_TAG = "FormationLabRoute"
THREAT_TAG = "FormationLabThreat"
FOLDER = "FormationLab"
SCHEMA = "codex.formation_layout/1"

CUBE = "/Engine/BasicShapes/Cube.Cube"
GRID = "/Engine/EngineMaterials/WorldGridMaterial.WorldGridMaterial"
FLOOR_THICKNESS = 20.0
START_Z = 100.0
TEXT_Z = 3.0

REPORT = []


def report(line):
    REPORT.append(str(line))
    if unreal is None:
        print(line, file=sys.stderr)


def load_layout(path):
    with open(path, encoding="utf-8") as f:
        layout = json.load(f)
    problems = []
    if layout.get("schema") != SCHEMA:
        problems.append("schema must be %s" % SCHEMA)
    for key in ("name", "bounds", "spawn", "walls", "zones", "routes"):
        if key not in layout:
            problems.append("missing %s" % key)
    if problems:
        raise ValueError("%s: %s (validate it in Training Ground first: npm test / the level-design department)" % (path, "; ".join(problems)))
    return layout


def plan(layout):
    """The actors to place, as plain dicts (pure: testable without Unreal). Units cm, yaw degrees (UE: atan2(dy, dx))."""
    gz = float(layout.get("ground_z", 0.0))
    (x0, y0), (x1, y1) = layout["bounds"]["min"], layout["bounds"]["max"]
    specs = [{
        "kind": "cube", "label": "Lab_Floor", "folder": "Floor",
        "location": [(x0 + x1) / 2.0, (y0 + y1) / 2.0, gz - FLOOR_THICKNESS / 2.0], "yaw": 0.0,
        "scale": [(x1 - x0) / 100.0, (y1 - y0) / 100.0, FLOOR_THICKNESS / 100.0],
    }]
    for w in layout["walls"]:
        (ax, ay), (bx, by) = w["a"], w["b"]
        length = math.hypot(bx - ax, by - ay)
        specs.append({
            "kind": "cube", "label": w["id"], "folder": "Walls",
            "location": [(ax + bx) / 2.0, (ay + by) / 2.0, gz + w["height"] / 2.0],
            "yaw": math.degrees(math.atan2(by - ay, bx - ax)),
            "scale": [length / 100.0, w["thickness"] / 100.0, w["height"] / 100.0],
        })
    sx, sy = layout["spawn"]["pos"]
    specs.append({"kind": "player_start", "label": "Lab_PlayerStart", "folder": "Base",
                  "location": [sx, sy, gz + START_Z], "yaw": float(layout["spawn"]["yaw"])})
    specs.append({"kind": "nav_bounds", "label": "Lab_NavMeshBounds", "folder": "Navigation",
                  "location": [(x0 + x1) / 2.0, (y0 + y1) / 2.0, gz + 200.0], "yaw": 0.0,
                  "scale": [(x1 - x0) / 200.0, (y1 - y0) / 200.0, 5.0]})
    for r in layout["routes"]:
        for n, (px, py) in enumerate(r["points"]):
            specs.append({"kind": "target_point", "label": "%s_%d" % (r["id"], n), "folder": "Routes/" + r["id"],
                          "location": [px, py, gz + 50.0], "yaw": 0.0, "tags": [ROUTE_TAG, r["id"]]})
        for n, t in enumerate(r.get("threats", [])):
            tx, ty = t["pos"]
            specs.append({"kind": "target_point", "label": "%s_threat_%d" % (r["id"], n), "folder": "Threats/" + r["id"],
                          "location": [tx, ty, gz + 100.0], "yaw": 0.0, "tags": [THREAT_TAG, r["id"], "since_s=%g" % t["since_s"]]})
    for z in layout["zones"]:
        cx = sum(p[0] for p in z["poly"]) / len(z["poly"])
        cy = sum(p[1] for p in z["poly"]) / len(z["poly"])
        specs.append({"kind": "text", "label": "Zone_" + z["id"], "folder": "Zones", "text": "%s (%s)" % (z["id"], z["kind"]),
                      "location": [cx, cy, gz + TEXT_Z], "yaw": 0.0})
    for p in layout.get("props", []):
        px, py = p["pos"]
        specs.append({"kind": "campfire" if p["kind"] == "heat_source" else "target_point", "label": p["id"], "folder": "Props",
                      "location": [px, py, gz], "yaw": 0.0})
    return specs


def vec(v):
    return [round(v.x, 1), round(v.y, 1), round(v.z, 1)]


class Placer:
    def __init__(self):
        self.actors = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
        self.cube = unreal.load_asset(CUBE)
        self.grid = unreal.load_asset(GRID)
        self.placed = 0

    def spawn(self, cls, spec, tags=None, folder_root=FOLDER):
        loc = unreal.Vector(*spec["location"])
        rot = unreal.Rotator(pitch=0.0, yaw=spec.get("yaw", 0.0), roll=0.0)
        actor = self.actors.spawn_actor_from_class(cls, loc, rot)
        actor.set_actor_label(spec["label"])
        actor.set_folder_path(folder_root + "/" + spec["folder"])
        actor.set_editor_property("tags", list(tags or [TAG]))
        if "scale" in spec:
            actor.set_actor_scale3d(unreal.Vector(*spec["scale"]))
        self.placed += 1
        return actor

    def place(self, spec):
        kind = spec["kind"]
        if kind == "cube":
            actor = self.spawn(unreal.StaticMeshActor, spec)
            comp = actor.static_mesh_component
            comp.set_static_mesh(self.cube)
            comp.set_material(0, self.grid)
        elif kind == "player_start":
            self.spawn(unreal.PlayerStart, spec)
        elif kind == "nav_bounds":
            self.spawn(unreal.NavMeshBoundsVolume, spec)
        elif kind == "target_point":
            self.spawn(unreal.TargetPoint, spec, tags=[TAG] + spec.get("tags", []))
        elif kind == "text":
            # Flat on the ground, readable from the top-down camera (pitch 90 lays the text down).
            spec = dict(spec)
            actor = self.spawn(unreal.TextRenderActor, spec)
            actor.set_actor_rotation(unreal.Rotator(pitch=90.0, yaw=0.0, roll=0.0), False)
            try:
                comp = actor.get_component_by_class(unreal.TextRenderComponent)
                comp.set_text(spec["text"])
                comp.set_editor_property("world_size", 60.0)
                comp.set_editor_property("horizontal_alignment", unreal.HorizTextAligment.EHTA_CENTER)
            except Exception as exc:  # cosmetic only
                report("REVIEW: zone label %s: %r" % (spec["label"], exc))
        elif kind == "campfire":
            cls = getattr(unreal, "CampfireActor", None)
            if cls is None:
                report("REVIEW: unreal.CampfireActor not found - %s placed as a TargetPoint" % spec["label"])
                cls = unreal.TargetPoint
            self.spawn(cls, spec)
        else:
            report("REVIEW: unknown spec kind %s" % kind)


def ensure_lighting(actors):
    """Sun, sky light, sky atmosphere, height fog - placed once (FormationLab_Env), never rebuilt, so hand tweaks stay."""
    have = [a for a in actors.get_all_level_actors() if ENV_TAG in [str(t) for t in a.tags]]
    if have:
        report("lighting: %d FormationLab_Env actors kept" % len(have))
        return
    p = Placer()
    env = [
        (unreal.DirectionalLight, {"label": "Lab_Sun", "folder": "Lighting", "location": [0, 0, 1000], "yaw": -30.0}),
        (unreal.SkyLight, {"label": "Lab_SkyLight", "folder": "Lighting", "location": [0, 0, 800], "yaw": 0.0}),
        (unreal.SkyAtmosphere, {"label": "Lab_SkyAtmosphere", "folder": "Lighting", "location": [0, 0, 0], "yaw": 0.0}),
        (unreal.ExponentialHeightFog, {"label": "Lab_HeightFog", "folder": "Lighting", "location": [0, 0, 0], "yaw": 0.0}),
    ]
    for cls, spec in env:
        actor = p.spawn(cls, spec, tags=[ENV_TAG])
        if cls is unreal.DirectionalLight:
            actor.set_actor_rotation(unreal.Rotator(pitch=-50.0, yaw=-30.0, roll=0.0), False)
        if cls is unreal.SkyLight:
            try:
                actor.light_component.set_editor_property("real_time_capture", True)
            except Exception as exc:
                report("REVIEW: sky light real-time capture: %r" % exc)
    report("lighting: placed %d FormationLab_Env actors" % p.placed)


def build():
    layout = load_layout(LAYOUT_FILE)
    specs = plan(layout)
    lib = unreal.EditorAssetLibrary
    level_editor = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
    if os.environ.get("CODEX_LAB_FRESH") == "1" and lib.does_asset_exist(TARGET_MAP):
        report("fresh: deleting %s -> %s" % (TARGET_MAP, lib.delete_asset(TARGET_MAP)))
    new_world = None
    if lib.does_asset_exist(TARGET_MAP):
        if not level_editor.load_level(TARGET_MAP):
            report("ERROR: could not load %s" % TARGET_MAP)
            return
        report("loaded %s" % TARGET_MAP)
    else:
        new_world = unreal.EditorLoadingAndSavingUtils.new_blank_map(False)
        report("new blank map for %s" % TARGET_MAP)
    actors = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)

    old = [a for a in actors.get_all_level_actors() if TAG in [str(t) for t in a.tags]]
    for a in old:
        actors.destroy_actor(a)
    report("removed %d actors of the previous run (tag %s)" % (len(old), TAG))

    ensure_lighting(actors)
    p = Placer()
    for spec in specs:
        p.place(spec)
    report("placed %d actors from %s (%d walls, %d zones, %d routes)" % (p.placed, os.path.basename(LAYOUT_FILE),
           len(layout["walls"]), len(layout["zones"]), len(layout["routes"])))

    starts = [a for a in actors.get_all_level_actors() if isinstance(a, unreal.PlayerStart)]
    if len(starts) != 1:
        report("REVIEW: %d PlayerStart actors in the map (expected 1)" % len(starts))

    # Saved navmesh actors stay empty at runtime when saved from a commandlet (docs/port/TRAPS.md).
    navmeshes = [a for a in actors.get_all_level_actors() if isinstance(a, unreal.RecastNavMesh)]
    for a in navmeshes:
        actors.destroy_actor(a)
    report("destroyed %d RecastNavMesh actors - bake with Scripts/bake_navmesh.ps1" % len(navmeshes))

    # A new map is saved under its path (as create_patrol_test_map.py); an existing one in place (as build_frozen_factory.py).
    saved = unreal.EditorLoadingAndSavingUtils.save_map(new_world, TARGET_MAP) if new_world else level_editor.save_current_level()
    report("saved %s: %s" % (TARGET_MAP, saved))


def flush_report():
    saved = unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_saved_dir())
    os.makedirs(saved + "Logs", exist_ok=True)
    with open(saved + "Logs/FormationLabLayout.txt", "w", encoding="utf-8") as f:
        f.write("\n".join(REPORT) + "\n")


def main():
    if unreal is None:
        if len(sys.argv) >= 2 and sys.argv[1] == "plan":
            path = sys.argv[2] if len(sys.argv) >= 3 else LAYOUT_FILE
            print(json.dumps(plan(load_layout(path)), indent=1))
            return
        print(__doc__)
        return
    report("build_formation_lab.py layout=%s target=%s (%s)" % (LAYOUT_FILE, TARGET_MAP, datetime.datetime.now().isoformat()))
    try:
        build()
    except Exception as exc:  # the report must be written whatever happens
        report("ERROR: %r" % exc)
    flush_report()


main()
