"""Genome = the numeric leaves of a PMC commander weights JSON (Content/Data/AI/pmc_commander.json).

Genes are addressed by JSON Pointer (RFC 6901), e.g. "/utility/flank/weight" or "/skills/2/score".
Non-numeric leaves (strings, bools, null) are never touched. Keys starting with "_" and the meta keys in
EXCLUDED_KEYS (version, schema, ...) are not genes either.

Bounds live in a sidecar `<weights>.bounds.json` (schema codex.trainer_bounds/1):
    {"schema": "codex.trainer_bounds/1", "default_rel": 0.5,
     "genes": {"/utility/flank/weight": {"min": 0.5, "max": 1.5, "step": 0.1, "frozen": false}}}
A gene missing from the sidecar gets the default bounds (+-default_rel of the baseline, clamped at 0 for a
non-negative baseline), so a new skill's weights join the genome automatically.
"""
from __future__ import annotations

import copy
import json
import os
from dataclasses import dataclass

BOUNDS_SCHEMA = "codex.trainer_bounds/1"
EXCLUDED_KEYS = {"version", "schema", "schema_version", "seed", "id"}


@dataclass(frozen=True)
class GeneSpec:
    """Search range of one gene. `step` is the gaussian mutation sigma at sigma_scale 1."""
    min: float
    max: float
    step: float
    is_int: bool = False
    frozen: bool = False


def _escape(key: str) -> str:
    return str(key).replace("~", "~0").replace("/", "~1")


def _unescape(token: str) -> str:
    return token.replace("~1", "/").replace("~0", "~")


def _is_number(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def flatten_numeric(doc, prefix: str = "") -> dict:
    """Ordered {pointer: value} of every numeric leaf that is a gene."""
    out = {}
    if isinstance(doc, dict):
        items = doc.items()
    elif isinstance(doc, list):
        items = enumerate(doc)
    else:
        return out
    for key, value in items:
        if isinstance(key, str) and (key.startswith("_") or key in EXCLUDED_KEYS):
            continue
        pointer = f"{prefix}/{_escape(key)}"
        if _is_number(value):
            out[pointer] = value
        elif isinstance(value, (dict, list)):
            out.update(flatten_numeric(value, pointer))
    return out


def set_leaf(doc, pointer: str, value) -> None:
    tokens = [_unescape(t) for t in pointer.split("/")[1:]]
    node = doc
    for token in tokens[:-1]:
        node = node[int(token)] if isinstance(node, list) else node[token]
    last = tokens[-1]
    if isinstance(node, list):
        node[int(last)] = value
    else:
        node[last] = value


def apply_genes(baseline_doc, genes: dict):
    """A copy of the baseline document with the gene values written in (structure and order preserved)."""
    doc = copy.deepcopy(baseline_doc)
    for pointer, value in genes.items():
        set_leaf(doc, pointer, value)
    return doc


def default_gene_bounds(value, rel: float = 0.5) -> dict:
    """+-rel around the baseline; a non-negative baseline is clamped at [0, x]; a zero baseline gets [0, 1]."""
    is_int = isinstance(value, int)
    v = float(value)
    if v == 0.0:
        lo, hi = 0.0, (5.0 if is_int else 1.0)
    elif v > 0.0:
        lo, hi = max(0.0, v * (1.0 - rel)), v * (1.0 + rel)
    else:
        lo, hi = v * (1.0 + rel), v * (1.0 - rel)
    step = (hi - lo) * 0.1
    if is_int:
        lo, hi, step = float(int(round(lo))), float(int(round(hi))), max(1.0, round(step))
        if hi <= lo:
            hi = lo + 1.0
    return {"min": round(lo, 6), "max": round(hi, 6), "step": round(step, 6)}


def generate_bounds(baseline_doc, rel: float = 0.5) -> dict:
    return {
        "schema": BOUNDS_SCHEMA,
        "default_rel": rel,
        "_comment": "Auto-generated by Scripts/Trainer (night trainer). Edit min/max/step per gene; "
                    "set \"frozen\": true to keep a gene at its baseline value. Genes missing here use default_rel.",
        "genes": {p: default_gene_bounds(v, rel) for p, v in flatten_numeric(baseline_doc).items()},
    }


def bounds_path_for(weights_path: str) -> str:
    root, _ = os.path.splitext(weights_path)
    return root + ".bounds.json"


def load_json(path: str):
    with open(path, "r", encoding="utf-8-sig") as f:
        return json.load(f)


def write_json(path: str, data) -> None:
    """Atomic write (tmp + replace) so a crash never leaves half a file behind."""
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=2)
        f.write("\n")
    os.replace(tmp, path)


def load_or_create_bounds(weights_path: str, bounds_path: str | None = None, rel: float = 0.5):
    """Returns (bounds_doc, created). Writes the sidecar next to the weights file when it is missing."""
    bounds_path = bounds_path or bounds_path_for(weights_path)
    if os.path.exists(bounds_path):
        return load_json(bounds_path), False
    bounds = generate_bounds(load_json(weights_path), rel)
    write_json(bounds_path, bounds)
    return bounds, True


def resolve_specs(baseline_genes: dict, bounds_doc: dict | None) -> dict:
    """{pointer: GeneSpec} for every baseline gene; sidecar entries override the defaults."""
    bounds_doc = bounds_doc or {}
    rel = float(bounds_doc.get("default_rel", 0.5))
    table = bounds_doc.get("genes", {})
    specs = {}
    for pointer, value in baseline_genes.items():
        d = default_gene_bounds(value, rel)
        d.update({k: v for k, v in table.get(pointer, {}).items() if k in ("min", "max", "step", "frozen")})
        lo, hi = float(d["min"]), float(d["max"])
        if hi < lo:
            lo, hi = hi, lo
        is_int = isinstance(value, int)
        step = float(d.get("step") or (hi - lo) * 0.1)
        specs[pointer] = GeneSpec(lo, hi, max(step, 1.0) if is_int else step, is_int, bool(d.get("frozen", False)))
    return specs


def clamp_gene(value, spec: GeneSpec):
    v = min(spec.max, max(spec.min, float(value)))
    if spec.is_int:
        return int(round(v))
    return round(v, 6)


def diff_genes(baseline: dict, other: dict) -> list:
    """[(pointer, baseline, other, delta_pct)] for the genes that differ."""
    rows = []
    for pointer, b in baseline.items():
        o = other.get(pointer, b)
        if o != b:
            pct = ((o - b) / abs(b) * 100.0) if b else None
            rows.append((pointer, b, o, pct))
    return rows
